/**
 * Onboarding States & Enum Definitions
 */

const ONBOARDING_STATES = Object.freeze({
    DRAFT: 'DRAFT',
    VALIDATING: 'VALIDATING',
    CONFIGURED: 'CONFIGURED',
    CONNECTING: 'CONNECTING',
    CONNECTED: 'CONNECTED',
    MONITORING: 'MONITORING',
    VALIDATION_FAILED: 'VALIDATION_FAILED',
    CONNECTION_FAILED: 'CONNECTION_FAILED',
    AUTHENTICATION_FAILED: 'AUTHENTICATION_FAILED',
    DISABLED: 'DISABLED',
    RETIRED: 'RETIRED'
});

const CONNECTION_TEST_RESULTS = Object.freeze({
    CONNECTED: 'CONNECTED',
    AUTHENTICATION_FAILED: 'AUTHENTICATION_FAILED',
    AUTHORIZATION_FAILED: 'AUTHORIZATION_FAILED',
    TIMEOUT: 'TIMEOUT',
    NETWORK_ERROR: 'NETWORK_ERROR',
    INVALID_CONFIGURATION: 'INVALID_CONFIGURATION',
    UNSUPPORTED: 'UNSUPPORTED',
    SECURITY_BLOCKED: 'SECURITY_BLOCKED',
    UNKNOWN: 'UNKNOWN'
});

const ADAPTER_TYPES = Object.freeze({
    HTTP: 'http',
    WEBHOOK: 'webhook',
    SDK: 'sdk',
    MOCK: 'mock',
    CUSTOM: 'custom'
});

const AUTH_TYPES = Object.freeze({
    NONE: 'none',
    API_KEY: 'apiKey',
    BEARER: 'bearer',
    BASIC: 'basic',
    CUSTOM: 'custom'
});

const VALID_ONBOARDING_TRANSITIONS = Object.freeze({
    [ONBOARDING_STATES.DRAFT]: [ONBOARDING_STATES.VALIDATING, ONBOARDING_STATES.VALIDATION_FAILED, ONBOARDING_STATES.CONFIGURED, ONBOARDING_STATES.DISABLED, ONBOARDING_STATES.RETIRED],
    [ONBOARDING_STATES.VALIDATING]: [ONBOARDING_STATES.CONFIGURED, ONBOARDING_STATES.VALIDATION_FAILED, ONBOARDING_STATES.DISABLED],
    [ONBOARDING_STATES.CONFIGURED]: [ONBOARDING_STATES.CONNECTING, ONBOARDING_STATES.CONNECTED, ONBOARDING_STATES.MONITORING, ONBOARDING_STATES.CONNECTION_FAILED, ONBOARDING_STATES.AUTHENTICATION_FAILED, ONBOARDING_STATES.DISABLED, ONBOARDING_STATES.RETIRED],
    [ONBOARDING_STATES.CONNECTING]: [ONBOARDING_STATES.CONNECTED, ONBOARDING_STATES.CONNECTION_FAILED, ONBOARDING_STATES.AUTHENTICATION_FAILED, ONBOARDING_STATES.DISABLED],
    [ONBOARDING_STATES.CONNECTED]: [ONBOARDING_STATES.MONITORING, ONBOARDING_STATES.DISABLED, ONBOARDING_STATES.RETIRED],
    [ONBOARDING_STATES.MONITORING]: [ONBOARDING_STATES.CONNECTED, ONBOARDING_STATES.DISABLED, ONBOARDING_STATES.RETIRED],
    [ONBOARDING_STATES.VALIDATION_FAILED]: [ONBOARDING_STATES.VALIDATING, ONBOARDING_STATES.DRAFT, ONBOARDING_STATES.CONFIGURED, ONBOARDING_STATES.RETIRED],
    [ONBOARDING_STATES.CONNECTION_FAILED]: [ONBOARDING_STATES.CONNECTING, ONBOARDING_STATES.CONFIGURED, ONBOARDING_STATES.RETIRED],
    [ONBOARDING_STATES.AUTHENTICATION_FAILED]: [ONBOARDING_STATES.CONNECTING, ONBOARDING_STATES.CONFIGURED, ONBOARDING_STATES.RETIRED],
    [ONBOARDING_STATES.DISABLED]: [ONBOARDING_STATES.CONFIGURED, ONBOARDING_STATES.CONNECTED, ONBOARDING_STATES.MONITORING, ONBOARDING_STATES.RETIRED],
    [ONBOARDING_STATES.RETIRED]: []
});

function isValidOnboardingTransition(fromState, toState) {
    if (!fromState || !toState) return false;
    if (fromState === toState) return true;
    const allowed = VALID_ONBOARDING_TRANSITIONS[fromState];
    return Array.isArray(allowed) && allowed.includes(toState);
}

module.exports = {
    ONBOARDING_STATES,
    CONNECTION_TEST_RESULTS,
    ADAPTER_TYPES,
    AUTH_TYPES,
    VALID_ONBOARDING_TRANSITIONS,
    isValidOnboardingTransition
};
