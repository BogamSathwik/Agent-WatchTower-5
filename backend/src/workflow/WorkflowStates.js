/**
 * Workflow States & Transition Logic
 * Deterministic lifecycle states for universal workflows.
 * Purely domain-agnostic.
 */

const WORKFLOW_STATES = Object.freeze({
    DRAFT: 'DRAFT',
    VALIDATING: 'VALIDATING',
    READY: 'READY',
    SCHEDULED: 'SCHEDULED',
    RUNNING: 'RUNNING',
    WAITING: 'WAITING',
    WAITING_APPROVAL: 'WAITING_APPROVAL',
    PAUSED: 'PAUSED',
    SUCCEEDED: 'SUCCEEDED',
    FAILED: 'FAILED',
    CANCELLED: 'CANCELLED',
    TIMED_OUT: 'TIMED_OUT',
    ROLLING_BACK: 'ROLLING_BACK',
    ROLLED_BACK: 'ROLLED_BACK'
});

const VALID_WORKFLOW_TRANSITIONS = Object.freeze({
    [WORKFLOW_STATES.DRAFT]: [WORKFLOW_STATES.VALIDATING, WORKFLOW_STATES.READY, WORKFLOW_STATES.CANCELLED],
    [WORKFLOW_STATES.VALIDATING]: [WORKFLOW_STATES.READY, WORKFLOW_STATES.DRAFT, WORKFLOW_STATES.FAILED],
    [WORKFLOW_STATES.READY]: [WORKFLOW_STATES.SCHEDULED, WORKFLOW_STATES.RUNNING, WORKFLOW_STATES.PAUSED, WORKFLOW_STATES.CANCELLED],
    [WORKFLOW_STATES.SCHEDULED]: [WORKFLOW_STATES.RUNNING, WORKFLOW_STATES.PAUSED, WORKFLOW_STATES.CANCELLED],
    [WORKFLOW_STATES.RUNNING]: [WORKFLOW_STATES.WAITING, WORKFLOW_STATES.WAITING_APPROVAL, WORKFLOW_STATES.PAUSED, WORKFLOW_STATES.SUCCEEDED, WORKFLOW_STATES.FAILED, WORKFLOW_STATES.TIMED_OUT, WORKFLOW_STATES.ROLLING_BACK, WORKFLOW_STATES.CANCELLED],
    [WORKFLOW_STATES.WAITING]: [WORKFLOW_STATES.RUNNING, WORKFLOW_STATES.PAUSED, WORKFLOW_STATES.CANCELLED, WORKFLOW_STATES.TIMED_OUT, WORKFLOW_STATES.FAILED],
    [WORKFLOW_STATES.WAITING_APPROVAL]: [WORKFLOW_STATES.RUNNING, WORKFLOW_STATES.PAUSED, WORKFLOW_STATES.CANCELLED, WORKFLOW_STATES.TIMED_OUT, WORKFLOW_STATES.FAILED, WORKFLOW_STATES.SUCCEEDED],
    [WORKFLOW_STATES.PAUSED]: [WORKFLOW_STATES.RUNNING, WORKFLOW_STATES.CANCELLED],
    [WORKFLOW_STATES.ROLLING_BACK]: [WORKFLOW_STATES.ROLLED_BACK, WORKFLOW_STATES.FAILED],
    [WORKFLOW_STATES.SUCCEEDED]: [WORKFLOW_STATES.RUNNING, WORKFLOW_STATES.READY],
    [WORKFLOW_STATES.FAILED]: [WORKFLOW_STATES.RUNNING, WORKFLOW_STATES.READY, WORKFLOW_STATES.ROLLING_BACK],
    [WORKFLOW_STATES.CANCELLED]: [WORKFLOW_STATES.RUNNING, WORKFLOW_STATES.READY],
    [WORKFLOW_STATES.TIMED_OUT]: [WORKFLOW_STATES.RUNNING, WORKFLOW_STATES.READY],
    [WORKFLOW_STATES.ROLLED_BACK]: [WORKFLOW_STATES.READY]
});

function isValidWorkflowState(state) {
    return Object.values(WORKFLOW_STATES).includes(state);
}

function isValidWorkflowTransition(currentState, newState) {
    if (!isValidWorkflowState(currentState) || !isValidWorkflowState(newState)) return false;
    if (currentState === newState) return true;
    const allowed = VALID_WORKFLOW_TRANSITIONS[currentState] || [];
    return allowed.includes(newState);
}

module.exports = {
    WORKFLOW_STATES,
    VALID_WORKFLOW_TRANSITIONS,
    isValidWorkflowState,
    isValidWorkflowTransition
};
