/**
 * Phase 17 — Agent Monitoring States & Transitions
 * Deterministic lifecycle states for end-to-end agent observability.
 */

const MONITORING_STATES = Object.freeze({
    UNKNOWN: 'UNKNOWN',
    HEALTHY: 'HEALTHY',
    DEGRADED: 'DEGRADED',
    UNHEALTHY: 'UNHEALTHY',
    OFFLINE: 'OFFLINE',
    RECOVERING: 'RECOVERING'
});

const MONITORING_EVENTS = Object.freeze({
    AGENT_MONITORING_STARTED: 'AGENT_MONITORING_STARTED',
    AGENT_HEALTH_CHECKED: 'AGENT_HEALTH_CHECKED',
    AGENT_HEALTH_CHANGED: 'AGENT_HEALTH_CHANGED',
    AGENT_DEGRADED: 'AGENT_DEGRADED',
    AGENT_UNHEALTHY: 'AGENT_UNHEALTHY',
    AGENT_OFFLINE: 'AGENT_OFFLINE',
    AGENT_TIMEOUT: 'AGENT_TIMEOUT',
    AGENT_EXECUTION_CHECKED: 'AGENT_EXECUTION_CHECKED',
    AGENT_EXECUTION_FAILED: 'AGENT_EXECUTION_FAILED',
    AGENT_RECOVERED: 'AGENT_RECOVERED',
    AGENT_MONITORING_STOPPED: 'AGENT_MONITORING_STOPPED'
});

const VALID_STATE_TRANSITIONS = Object.freeze({
    [MONITORING_STATES.UNKNOWN]: [
        MONITORING_STATES.HEALTHY,
        MONITORING_STATES.DEGRADED,
        MONITORING_STATES.UNHEALTHY,
        MONITORING_STATES.OFFLINE
    ],
    [MONITORING_STATES.HEALTHY]: [
        MONITORING_STATES.HEALTHY,
        MONITORING_STATES.DEGRADED,
        MONITORING_STATES.UNHEALTHY,
        MONITORING_STATES.OFFLINE
    ],
    [MONITORING_STATES.DEGRADED]: [
        MONITORING_STATES.HEALTHY,
        MONITORING_STATES.DEGRADED,
        MONITORING_STATES.UNHEALTHY,
        MONITORING_STATES.OFFLINE,
        MONITORING_STATES.RECOVERING
    ],
    [MONITORING_STATES.UNHEALTHY]: [
        MONITORING_STATES.UNHEALTHY,
        MONITORING_STATES.OFFLINE,
        MONITORING_STATES.RECOVERING,
        MONITORING_STATES.HEALTHY
    ],
    [MONITORING_STATES.OFFLINE]: [
        MONITORING_STATES.OFFLINE,
        MONITORING_STATES.RECOVERING,
        MONITORING_STATES.HEALTHY
    ],
    [MONITORING_STATES.RECOVERING]: [
        MONITORING_STATES.HEALTHY,
        MONITORING_STATES.DEGRADED,
        MONITORING_STATES.UNHEALTHY,
        MONITORING_STATES.OFFLINE
    ]
});

function isValidMonitoringState(state) {
    return Object.values(MONITORING_STATES).includes(state);
}

function isValidTransition(fromState, toState) {
    if (!isValidMonitoringState(fromState) || !isValidMonitoringState(toState)) {
        return false;
    }
    if (fromState === toState) return true;
    const allowed = VALID_STATE_TRANSITIONS[fromState] || [];
    return allowed.includes(toState);
}

module.exports = {
    MONITORING_STATES,
    MONITORING_EVENTS,
    VALID_STATE_TRANSITIONS,
    isValidMonitoringState,
    isValidTransition
};
