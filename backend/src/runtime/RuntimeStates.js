/**
 * Standardized Operational Runtime Lifecycle States
 * Defines domain-agnostic states for live runtime management.
 */

const RUNTIME_STATES = Object.freeze({
    REGISTERED: 'REGISTERED',
    INITIALIZING: 'INITIALIZING',
    READY: 'READY',
    STARTING: 'STARTING',
    RUNNING: 'RUNNING',
    PAUSED: 'PAUSED',
    STOPPING: 'STOPPING',
    STOPPED: 'STOPPED',
    DEGRADED: 'DEGRADED',
    FAILED: 'FAILED',
    RESTARTING: 'RESTARTING',
    DISABLED: 'DISABLED',
    RETIRED: 'RETIRED'
});

const RUNTIME_COMMANDS = Object.freeze({
    START: 'START',
    STOP: 'STOP',
    RESTART: 'RESTART',
    PAUSE: 'PAUSE',
    RESUME: 'RESUME',
    STATUS: 'STATUS',
    HEALTH_CHECK: 'HEALTH_CHECK',
    CAPABILITIES: 'CAPABILITIES',
    EXECUTE: 'EXECUTE'
});

// Valid operational transitions
const VALID_TRANSITIONS = {
    [RUNTIME_STATES.REGISTERED]: [RUNTIME_STATES.INITIALIZING, RUNTIME_STATES.READY, RUNTIME_STATES.STARTING, RUNTIME_STATES.DISABLED, RUNTIME_STATES.RETIRED],
    [RUNTIME_STATES.INITIALIZING]: [RUNTIME_STATES.READY, RUNTIME_STATES.STARTING, RUNTIME_STATES.FAILED, RUNTIME_STATES.STOPPED],
    [RUNTIME_STATES.READY]: [RUNTIME_STATES.STARTING, RUNTIME_STATES.RUNNING, RUNTIME_STATES.DISABLED, RUNTIME_STATES.RETIRED],
    [RUNTIME_STATES.STARTING]: [RUNTIME_STATES.RUNNING, RUNTIME_STATES.DEGRADED, RUNTIME_STATES.FAILED, RUNTIME_STATES.STOPPED],
    [RUNTIME_STATES.RUNNING]: [RUNTIME_STATES.PAUSED, RUNTIME_STATES.STOPPING, RUNTIME_STATES.STOPPED, RUNTIME_STATES.DEGRADED, RUNTIME_STATES.FAILED, RUNTIME_STATES.RESTARTING],
    [RUNTIME_STATES.PAUSED]: [RUNTIME_STATES.RUNNING, RUNTIME_STATES.STOPPING, RUNTIME_STATES.STOPPED, RUNTIME_STATES.FAILED],
    [RUNTIME_STATES.STOPPING]: [RUNTIME_STATES.STOPPED, RUNTIME_STATES.FAILED],
    [RUNTIME_STATES.STOPPED]: [RUNTIME_STATES.STARTING, RUNTIME_STATES.RUNNING, RUNTIME_STATES.READY, RUNTIME_STATES.DISABLED, RUNTIME_STATES.RETIRED],
    [RUNTIME_STATES.DEGRADED]: [RUNTIME_STATES.RUNNING, RUNTIME_STATES.RESTARTING, RUNTIME_STATES.STOPPING, RUNTIME_STATES.STOPPED, RUNTIME_STATES.FAILED],
    [RUNTIME_STATES.FAILED]: [RUNTIME_STATES.RESTARTING, RUNTIME_STATES.STARTING, RUNTIME_STATES.STOPPED, RUNTIME_STATES.DISABLED],
    [RUNTIME_STATES.RESTARTING]: [RUNTIME_STATES.RUNNING, RUNTIME_STATES.DEGRADED, RUNTIME_STATES.FAILED, RUNTIME_STATES.STOPPED],
    [RUNTIME_STATES.DISABLED]: [RUNTIME_STATES.READY, RUNTIME_STATES.STOPPED, RUNTIME_STATES.RETIRED],
    [RUNTIME_STATES.RETIRED]: []
};

class RuntimeStateMachine {
    static canTransition(fromState, toState) {
        if (!fromState || !toState) return false;
        if (fromState === toState) return true; // idempotency
        const allowed = VALID_TRANSITIONS[fromState] || [];
        return allowed.includes(toState);
    }
}

module.exports = {
    RUNTIME_STATES,
    RUNTIME_COMMANDS,
    VALID_TRANSITIONS,
    RuntimeStateMachine
};
